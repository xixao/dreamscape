import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import postcss from "postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
function files(dir) {
  return fs.readdirSync(path.join(root, dir), { withFileTypes: true })
    .flatMap((e) => e.isDirectory() ? files(`${dir}/${e.name}`) : [`${dir}/${e.name}`])
    .sort();
}
const sources = [...files("app"), ...files("components"), ...files("lib")]
  .filter((f) => /\.tsx?$/.test(f));
const product = (f) => !f.startsWith("components/ui/");
const nativeTags = new Set(["button", "input", "textarea", "select", "label", "details", "summary", "svg", "a", "progress", "img"]);
const imports = [], native = [], usages = [], inlineStyles = [];
const lineAt = (sf, n) => sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1;
function resolve(from, specifier) {
  const base = specifier.startsWith("@/") ? specifier.slice(2)
    : specifier.startsWith(".") ? path.posix.normalize(path.posix.join(path.posix.dirname(from), specifier)) : null;
  return base && [base, `${base}.tsx`, `${base}.ts`, `${base}/index.tsx`, `${base}/index.ts`]
    .find((f) => fs.existsSync(path.join(root, f)) && fs.statSync(path.join(root, f)).isFile());
}
for (const file of sources) {
  const sf = ts.createSourceFile(file, read(file), ts.ScriptTarget.Latest, true);
  const bindings = new Map();
  for (const n of sf.statements) {
    if ((!ts.isImportDeclaration(n) && !ts.isExportDeclaration(n)) || !n.moduleSpecifier || !ts.isStringLiteral(n.moduleSpecifier)) continue;
    const specifier = n.moduleSpecifier.text, target = resolve(file, specifier);
    imports.push({ file, line: lineAt(sf, n), specifier, target: target || null });
    if (!ts.isImportDeclaration(n) || !n.importClause) continue;
    const clause = n.importClause;
    if (clause.name) bindings.set(clause.name.text, { target, specifier, symbol: "default" });
    if (clause.namedBindings && ts.isNamedImports(clause.namedBindings)) {
      for (const b of clause.namedBindings.elements) bindings.set(b.name.text, { target, specifier, symbol: b.propertyName?.text || b.name.text });
    }
  }
  function visit(n) {
    if (ts.isJsxOpeningElement(n) || ts.isJsxSelfClosingElement(n)) {
      const tag = n.tagName.getText(sf), line = lineAt(sf, n);
      const attrs = n.attributes.properties.filter(ts.isJsxAttribute);
      const attribute = (name) => attrs.find((a) => a.name.getText(sf) === name)?.initializer?.getText(sf) || null;
      if (product(file) && nativeTags.has(tag)) native.push({ file, line, tag, className: attribute("className"), type: attribute("type"), ariaLabel: attribute("aria-label") });
      if (product(file) && attribute("style")) inlineStyles.push({ file, line, tag, value: attribute("style") });
      const binding = bindings.get(tag);
      if (binding) usages.push({ file, line, tag, ...binding });
    }
    ts.forEachChild(n, visit);
  }
  visit(sf);
}
const css = postcss.parse(read("app/globals.css"));
const tokens = [], literals = [], rules = new Map();
css.walkDecls((d) => {
  if (d.prop.startsWith("--")) tokens.push({ line: d.source.start.line, selector: d.parent.selector || d.parent.name, name: d.prop, value: d.value });
  else if (/#[\da-f]{3,8}\b|\b(?:rgb|hsl)a?\(/i.test(d.value)) literals.push({ line: d.source.start.line, selector: d.parent.selector, name: d.prop, value: d.value });
});
css.walkRules((r) => {
  const contexts = []; let p = r.parent;
  while (p && p.type !== "root") { if (p.type === "atrule") contexts.unshift(`@${p.name} ${p.params}`); p = p.parent; }
  const key = `${contexts.join(" > ")} | ${r.selector}`;
  if (!rules.has(key)) rules.set(key, []);
  rules.get(key).push(r.source.start.line);
});
const repeatedSelectors = [...rules].filter(([, lines]) => lines.length > 1).map(([selector, lines]) => ({ selector, lines }));
const uiFiles = files("components/ui").filter((f) => f.endsWith(".tsx"));
const reachable = new Set();
function mark(file) { if (reachable.has(file)) return; reachable.add(file); imports.filter((i) => i.file === file && i.target).forEach((i) => mark(i.target)); }
sources.filter((f) => f.startsWith("app/")).forEach(mark);
const report = { scope: "Static source inventory; JSX sites, not runtime instance counts. Library internals excluded from native-control candidates. No visual or accessibility certification.", sources: sources.length, native, usages, imports, inlineStyles, tokens, literals, repeatedSelectors, uiFiles, uiReachableFromApp: uiFiles.filter((f) => reachable.has(f)) };
const link = (file, line) => `[${file}:${line}](../${file}#L${line})`;
const lines = ["# Atomic Source Audit", "", "Generated by `node scripts/audit-design-system.mjs`. Run with `--check` to detect a stale report.", "", report.scope, "", "## Summary", "", `- ${sources.length} TypeScript/TSX source files scanned.`, `- ${native.length} native element sites outside UI-library internals (candidates, not automatic violations).`, `- ${uiFiles.length} UI-library modules available; ${report.uiReachableFromApp.length} reachable through static imports from app source.`, `- ${literals.length} literal-color declarations outside custom-property definitions.`, `- ${repeatedSelectors.length} repeated selector/context groups; intentional cascade rules may be included.`, "", "## Shared Sources Actually Used", "", "| Source | JSX sites in product code | Consumers |", "| --- | ---: | --- |"];
const targets = [...new Set(usages.filter((u) => product(u.file) && u.target?.startsWith("components/")).map((u) => u.target))].sort();
for (const target of targets) {
  const found = usages.filter((u) => product(u.file) && u.target === target);
  lines.push(`| [${target}](../${target}) | ${found.length} | ${[...new Set(found.map((u) => u.file))].join(", ")} |`);
}
lines.push("", "## Direct Native Elements", "", "Labels, links, disclosure elements and diagram SVG can be valid native composition. Review semantics before replacing them.", "", "| Element | Sites | Locations |", "| --- | ---: | --- |");
for (const tag of nativeTags) {
  const found = native.filter((n) => n.tag === tag);
  if (found.length) lines.push(`| ${tag} | ${found.length} | ${found.map((n) => link(n.file, n.line)).join(", ")} |`);
}
lines.push("", "## Library Availability Is Not Adoption", "", "Reachable from app source:", "", report.uiReachableFromApp.map((f) => `- ${f}`).join("\n"), "", "Not reachable through this static import graph (do not delete automatically):", "", uiFiles.filter((f) => !reachable.has(f)).map((f) => `- ${f}`).join("\n"), "", "## Dynamic Inline Styles", "", ...inlineStyles.map((s) => `- ${link(s.file, s.line)}: ${s.tag}; inspect positioning/transform intent before tokenizing.`), "", "## Repeated CSS Selector Groups", "", ...repeatedSelectors.map((r) => `- \`${r.selector}\`: lines ${r.lines.join(", ")}`), "", "## Limits", "", "- Counts are static JSX sites, including conditional branches, not mounted controls or unique users.", "- Static imports/re-exports are followed; dynamic loading and computed component references are not resolved.", "- Native controls are candidates. An instrumented aria-disabled control can intentionally differ from a disabled native control.", "- Shared imports do not prove identical styling, keyboard behavior, contrast, focus management, or permissions.", "- Full import, usage, native-site, theme-token and literal-color evidence is in atomic-source-audit.json.", "");
const outputs = { "docs/atomic-source-audit.json": JSON.stringify(report, null, 2) + "\n", "docs/atomic-source-audit.md": lines.join("\n") };
let stale = false;
for (const [file, value] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(path.join(root, file)) || read(file) !== value) { console.error(`Stale: ${file}`); stale = true; }
  } else { fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); fs.writeFileSync(path.join(root, file), value); }
}
if (stale) process.exitCode = 1;
else console.log(`Atomic inventory ${process.argv.includes("--check") ? "current" : "generated"}: ${native.length} native sites, ${targets.length} shared control sources, ${report.uiReachableFromApp.length}/${uiFiles.length} library modules reachable.`);
